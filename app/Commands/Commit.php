<?php

namespace App\Commands;

use App\Enums\GeminiModels;
use App\GoogleGemini;
use App\Prompt;
use Exception;
use LaravelZero\Framework\Commands\Command;
use Symfony\Component\Process\Exception\ProcessFailedException;
use Symfony\Component\Process\Process;

use function Laravel\Prompts\confirm;
use function Laravel\Prompts\select;
use function Laravel\Prompts\spin;
use function Laravel\Prompts\textarea;

class Commit extends Command
{
    /**
     * Constant representing the action to modify the commit message.
     *
     * @var string
     */
    protected const MODIFY_COMMIT = 'modify_commit';

    /**
     * Constant representing the action to accept the commit message.
     *
     * @var string
     */
    protected const ACCEPT_COMMIT = 'accept_commit';

    /**
     * Constant representing the action to regenerate the commit message.
     *
     * @var string
     */
    protected const REGENERATE_COMMIT = 'regenerate_commit';

    /**
     * The signature of the command.
     *
     * @var string
     */
    protected $signature = 'commit
                            {--m|model= : Model ID. Default: gemini-3.1-flash-lite. Gemini 4: gemini-4-carbon, gemini-4-argon, gemini-4-neon, gemini-4-hydrogen}
                            {--t|temperature= : Sampling temperature. Default: 0.3. Not supported on Gemini 4}
                            {--k|tokens= : Max output tokens. Defaults: 32768 for Carbon/Argon, 65536 for Neon/Hydrogen; 100 or 65536 for older models}
                            {--thinking= : Model-specific thinking level. Gemini 4: LOW (default), MEDIUM, HIGH; Neon/Hydrogen also accept XHIGH}';

    /**
     * The description of the command.
     *
     * @var string
     */
    protected $description = 'Automatically generate commit messages';

    /**
     * The model selected with `--model`, or null to use the client default.
     *
     * @var GeminiModels|null
     */
    protected ?GeminiModels $model;

    /**
     * The sampling temperature override, or null if no override was supplied.
     *
     * @var float|null
     */
    protected ?float $temperature;

    /**
     * The output token limit override, or null to use the model's default.
     *
     * @var int|null
     */
    protected ?int $maxTokens;

    /**
     * The selected or default uppercase thinking level, or null if the model has no thinking levels.
     *
     * @var string|null
     */
    protected ?string $thinking;

    /**
     * The current commit message, either generated by Gemini or edited by the user.
     *
     * @var string
     */
    protected string $message;

    /**
     * Generates a message from staged changes and prompts the user before committing. Prints exception messages to the console.
     *
     * @return void
     */
    public function handle(): void
    {
        try {
            $this->setCommandOptions();
            $this->generateCommitMessage();
            $this->handleUserResponse();
        } catch (Exception $e) {
            $this->error($e->getMessage());
        }
    }

    /**
     * Resolves the `--model` option to a supported Gemini model.
     *
     * @return GeminiModels|null The selected model, or null if the option has no value.
     *
     * @throws Exception If the option does not match a model.
     */
    private function getModel(): ?GeminiModels
    {
        $modelOption = $this->option('model');

        if ($modelOption === null) {
            return null;
        }

        $model = GeminiModels::tryFromCliFlag($modelOption);

        if ($model === null) {
            $supportedModels = implode("\n\t", GeminiModels::casesForCli());
            throw new Exception("Wrong model option!\nCurrently supported models are:\n\t{$supportedModels}");
        }

        return $model;
    }

    /**
     * Reads `--temperature`. Gemini 4 models reject the flag even without a value.
     *
     * @return float|null The supplied temperature, or null if the option has no value.
     *
     * @throws Exception If the model rejects the flag or the supplied value is not a float between 0 and 2 inclusive.
     */
    private function getTemperature(): ?float
    {
        $temperatureOption = $this->option('temperature');

        if ($this->model?->isGemini4() && ($temperatureOption !== null || $this->input->hasParameterOption(['--temperature', '-t'], true))) {
            throw new Exception("--temperature is not supported for {$this->model->value}!");
        }

        if ($temperatureOption === null) {
            return null;
        }

        $temperature = (float) $temperatureOption;

        if (! is_float($temperatureOption) || $temperature < 0 || $temperature > 2) {
            throw new Exception('Temperature must be a positive float between 0 and 2!');
        }

        return $temperature;
    }

    /**
     * Casts the `--tokens` value to an integer and checks that it is positive.
     *
     * @return int|null The output token limit, or null if the option has no value.
     *
     * @throws Exception If the cast result is zero or negative.
     */
    private function getMaxTokens(): ?int
    {
        $maxTokensOption = $this->option('tokens');

        if ($maxTokensOption === null) {
            return null;
        }

        $maxTokens = (int) $maxTokensOption;

        if ($maxTokens <= 0) {
            throw new Exception('Maximum number of tokens must be a positive integer more than 0!');
        }

        return $maxTokens;
    }

    /**
     * Resolves `--thinking` against the selected model or the default model.
     *
     * @return string|null The supplied level in uppercase, the model's first supported level if omitted, or null if omitted and the model has no levels.
     *
     * @throws Exception If the supplied level is not supported by the model.
     */
    private function getThinking(): ?string
    {
        $thinking = $this->option('thinking');
        $model = $this->model ?: GeminiModels::DEFAULT_MODEL;
        $valid = $model->supportedThinkingLevels();

        if ($thinking === null) {
            return ! empty($valid) ? $valid[0] : null;
        }

        $thinking = strtoupper($thinking);

        if (empty($valid)) {
            throw new Exception('Thinking mode is only supported for Gemini 3 models!');
        }

        if (! in_array($thinking, $valid)) {
            throw new Exception("Invalid thinking level for {$model->value}! Supported: " . implode(', ', $valid));
        }

        return $thinking;
    }

    /**
     * Validates the command options and stores them for message generation.
     *
     * @return void
     *
     * @throws Exception If an option is invalid or unsupported.
     */
    private function setCommandOptions(): void
    {
        $this->model = $this->getModel();
        $this->temperature = $this->getTemperature();
        $this->maxTokens = $this->getMaxTokens();
        $this->thinking = $this->getThinking();
    }

    /**
     * Sends the staged diff to Gemini and stores the returned message while displaying a spinner.
     *
     * @return void
     *
     * @throws Exception If the API key is missing, there are no staged changes, or the diff or request fails.
     */
    private function generateCommitMessage(): void
    {
        if (config('gemini.api_key') === null) {
            throw new Exception('API_KEY is not set!');
        }

        $googleGemini = new GoogleGemini(
            apiKey: config('gemini.api_key'),
            model: $this->model,
            temperature: $this->temperature,
            maxTokens: $this->maxTokens,
            thinking: $this->thinking
        );

        $this->message = spin(
            message: 'Generating your commit message...',
            callback: fn () => $googleGemini->generate(messages: Prompt::getPrompt())
        );
    }

    /**
     * Displays the current message and lets the user regenerate or edit it. Runs Git only after confirmation.
     *
     * @return void
     *
     * @throws ProcessFailedException If the commit fails.
     */
    private function handleUserResponse(): void
    {
        $this->warn($this->message);

        $action = $this->askWhatToDoWithCommit();

        if ($action === Commit::REGENERATE_COMMIT) {
            $this->generateCommitMessage();
            $this->handleUserResponse();

            return;
        }

        if ($action === Commit::MODIFY_COMMIT) {
            $this->getNewCommitMessage();
            $this->warn($this->message);
        }

        if ($this->confirmCommit()) {
            $this->commitChanges();

            return;
        }

        $this->discardCommit();
    }

    /**
     * Asks whether to edit, keep, or regenerate the current message.
     *
     * @return string The selected action key.
     */
    private function askWhatToDoWithCommit(): string
    {
        return select(
            label: 'Do you want to modify it?',
            options: [
                Commit::MODIFY_COMMIT => 'Yes',
                Commit::ACCEPT_COMMIT => 'No',
                Commit::REGENERATE_COMMIT => 'Regenerate',
            ],
            default: Commit::ACCEPT_COMMIT
        );
    }

    /**
     * Prompts the user to edit the current message and stores the result. Requires at least six bytes.
     *
     * @return void
     */
    private function getNewCommitMessage(): void
    {
        $this->message = textarea(
            label: 'Please enter the new commit message.',
            required: 'Commit message is required',
            default: $this->message,
            validate: fn (string $value) => match (true) {
                strlen($value) < 6 => 'Your commit should be longer than 6 characters.',
                default => null
            }
        );
    }

    /**
     * Asks whether to commit with the current message. The prompt defaults to yes.
     *
     * @return bool Whether the user confirms the commit.
     */
    private function confirmCommit(): bool
    {
        return confirm(
            label: 'Do you accept this commit message?',
            default: true
        );
    }

    /**
     * Runs `git commit` with the current message and reports success.
     *
     * @return void
     *
     * @throws ProcessFailedException If Git exits unsuccessfully.
     */
    private function commitChanges(): void
    {
        $command = ['git', 'commit', '-m', $this->message];
        $process = new Process($command);
        $process->run();

        if (! $process->isSuccessful()) {
            throw new ProcessFailedException($process);
        }

        $this->info('Commit successful!');
    }

    /**
     * Prints a notice that the message was discarded. Does not run Git.
     *
     * @return void
     */
    private function discardCommit(): void
    {
        $this->info('Commit message discarded.');
    }
}
